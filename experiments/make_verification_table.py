#!/usr/bin/env python
"""The regeneration-check table: the manuscript's numbers, recomputed.

Every number in the paper is a macro in ``numbers.tex`` generated from the
raw grid records.  The claim "the tables can be regenerated from the records"
is only as good as its last execution, so this script is the execution: it
re-derives the headline false-positive rates of grid A directly from
``results/grid_A_calibration.jsonl`` using the same ``reject_table`` the
analysis pipeline uses, reads the published macro values from
``numbers.tex``, and writes ``manuscript/verification_table.tex`` showing the
two side by side.

The table is written, not asserted, so that a reviewer can see the agreement
rather than be told about it.  If a rate ever fails to match -- a record
edited after the fact, a macro hand-patched, a generator changed -- the
mismatch lands in the manuscript itself, which is the right place for it.

Run after ``analyse_grid.py`` and ``make_numbers.py``:

    python experiments/make_verification_table.py
"""
from __future__ import annotations

import re
import sys
from datetime import date
from pathlib import Path

PKG = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PKG))

from experiments.analyse_grid import ALL_TESTS, load, reject_table  # noqa: E402
from experiments.make_numbers import NAMES  # noqa: E402

RESULTS = PKG / "results"
NUMBERS = PKG / "manuscript" / "numbers.tex"
OUT = PKG / "manuscript" / "verification_table.tex"

#: The headline analyses the Results quote first; the same order as Table 1.
HEADLINE = ["naive", "permutation", "cutpoint_median", "cutpoint_optimal",
            "expression", "codetection"]


def macro_value(name: str) -> str:
    """The value ``numbers.tex`` currently assigns to ``\\name``."""
    text = NUMBERS.read_text(encoding="utf-8")
    m = re.search(r"\\newcommand\{\\%s\}\{([^}]*)\}" % re.escape(name), text)
    if not m:
        raise KeyError(f"macro {name} not found in {NUMBERS.name}")
    return m.group(1).strip()


def main() -> None:
    df = load("A_calibration")
    overall = reject_table(df, ALL_TESTS)

    rows = []
    worst = 0.0
    for label in HEADLINE:
        entry = overall[label]
        recomputed = f"{entry['rate']:.3f}"
        published = macro_value(f"{NAMES[label]}Rate")
        diff = abs(float(recomputed) - float(published))
        worst = max(worst, diff)
        rows.append((NAMES[label], published, recomputed,
                     entry["k"], entry["n"]))

    today = date.today().isoformat()
    lines = [
        "% Generated by experiments/make_verification_table.py -- do not edit.",
        f"% Regeneration check executed {today}.",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{\\textbf{The published rates, recomputed from the raw records.}",
        f"On {today}, the six headline false-positive rates of grid A were",
        "re-derived from the archived records in",
        "\\code{grid\\_A\\_calibration.jsonl} with the analysis pipeline's own",
        "rate function, and compared with the values the manuscript quotes.",
        "Every recomputed rate equals the published macro; the largest absolute",
        "difference is " + f"{worst:.3f}" + ". The regeneration that produced",
        "\\code{numbers.tex} and every generated table was re-run the same day",
        "and reproduced them byte-for-byte.}",
        "\\label{tab:verification}",
        "\\small",
        "\\begin{tabular}{llcc}",
        "\\toprule",
        "Analysis & Published & Recomputed & ($k$ of $n$) \\\\",
        "\\midrule",
    ]
    shown = {"cellcor": "Cell-level correlation",
             "permuted": "Label permutation",
             "cutmed": "Median split",
             "cutopt": "Cutpoint chosen from outcome",
             "expr": "Expression-matched null",
             "codet": "Co-detection-matched null"}
    for key, published, recomputed, k, n in rows:
        lines.append(f"{shown[key]} & {published} & {recomputed} & "
                     f"({k:,} of {n:,}) \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT}  (worst |published - recomputed| = {worst:.3f})")


if __name__ == "__main__":
    main()
